/**
 * 특정 실천 분야의 3단계 위계 노드 목록 조회
 * @param {string} domainId - 예: '01_사회복지관', '02_노인복지'
 * @returns {Array} 해당 분야의 노드 배열
 */
function getHierarchyByDomain(domainId) {
  if (!domainId) return WELFARE_HIERARCHY_NODES;
  return WELFARE_HIERARCHY_NODES.filter(n => n.domainId === domainId);
}

/**
 * 실천 분야의 플랫 노드를 계층형 트리 객체로 변환
 * Structure: { [level1]: { [level2]: [ level3_nodes ] } }
 * @param {string} domainId
 * @returns {Object} 중첩된 계층 트리
 */
function getHierarchyTree(domainId) {
  const nodes = getHierarchyByDomain(domainId);
  const tree = {};

  nodes.forEach(node => {
    const l1 = node.level1;
    const l2 = node.level2;

    if (!tree[l1]) {
      tree[l1] = {};
    }
    if (!tree[l1][l2]) {
      tree[l1][l2] = [];
    }
    tree[l1][l2].push(node);
  });

  return tree;
}

/**
 * 전체 12대 분야를 포괄하는 종합 트리 맵 생성
 * Structure: { [domainId]: { info: domainInfo, tree: { [level1]: { [level2]: [ nodes ] } } } }
 */
function getFullHierarchyTreeMap() {
  const fullMap = {};
  WELFARE_HIERARCHY_DOMAINS.forEach(dom => {
    fullMap[dom.id] = {
      info: dom,
      tree: getHierarchyTree(dom.id),
      totalServices: getHierarchyByDomain(dom.id).length
    };
  });
  return fullMap;
}

/**
 * 키워드 기반 소분류/중분류/대분류/설명 실시간 검색
 * @param {string} query - 검색어
 * @returns {Array} 매칭된 노드 목록
 */
function searchHierarchyNodes(query) {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  
  return WELFARE_HIERARCHY_NODES.filter(n => {
    return (
      (n.level3 && n.level3.toLowerCase().includes(q)) ||
      (n.level2 && n.level2.toLowerCase().includes(q)) ||
      (n.level1 && n.level1.toLowerCase().includes(q)) ||
      (n.facilityType && n.facilityType.toLowerCase().includes(q)) ||
      (n.summary && n.summary.toLowerCase().includes(q)) ||
      (n.guidelineRef && n.guidelineRef.file && n.guidelineRef.file.toLowerCase().includes(q))
    );
  });
}

/**
 * 데이터베이스 통계 반환
 */
function getHierarchyStats() {
  const totalNodes = WELFARE_HIERARCHY_NODES.length;
  const totalDomains = WELFARE_HIERARCHY_DOMAINS.length;
  const facilities = new Set(WELFARE_HIERARCHY_NODES.map(n => n.facilityType));
  const files = new Set(WELFARE_HIERARCHY_NODES.map(n => n.guidelineRef.file));
  
  return {
    totalDomains,
    totalNodes,
    uniqueFacilitiesCount: facilities.size,
    uniqueGuidelinesCount: files.size
  };
}

