/**
 * 단일 텍스트 대상 12대 세분화 분야 규칙 매칭
 */
function matchFieldRules(text) {
    // 1. 정신건강 (정신병원/정신의료기관·지역사회전환시설을 일반 병원보다 먼저 판별)
    if (/(정신건강|정신보건|정신재활|정신요양|정신병원|정신의료|지역사회전환시설|정신응급|자살예방|중독관리|생명존중|마음건강|마인드링크|트라우마)/.test(text)) {
        return 'mental-health';
    }
    // 2. 의료사회복지
    if (/(의료사회복지|병원|사회사업팀|의료원|요양병원|재활병원|호스피스|대한의료)/.test(text)) {
        return 'medical';
    }
    // 3. 학교·교육복지
    if (/(학교사회복지|교육복지|교육청|wee센터|wee클래스|학생맞춤|초등학교|중학교|고등학교)/.test(text)) {
        return 'school';
    }
    // 4. 교정·공공·공단
    if (/(공기업|공공기관|전담공무원|사회서비스원|건보공단|국민건강보험|국민연금|근로복지공단|사회보장정보원|교정|보호관찰|법무보호|스마일센터|범죄피해자)/.test(text)) {
        return 'public-justice';
    }
    // 5. 국제구호·NGO (공동모금회와 겹치지 않도록 '모금' 단일어 대신 NGO/국제구호 고유 키워드 사용)
    if (/(ngo|국제구호|kcoc|국제개발|해외사업|월드비전|굿네이버스|세이브더칠드런|유니세프|옥스팜|기아대책)/.test(text)) {
        return 'ngo';
    }
    // 6. 기업 CSR·공익재단
    if (/(csr|사회공헌|esg|복지재단|공익재단|장학재단|공동모금회|사랑의열매|아름다운재단|임팩트|소셜벤처)/.test(text)) {
        return 'csr-foundation';
    }
    // 7. 가족·여성·성평등
    if (/(가족센터|건강가정|다문화|한부모|미혼모|모자가족|부자가족|성평등|여성가족|여성복지|여성권익|여성긴급|여성쉼터|성폭력|가정폭력|성매매|스토킹|해바라기센터|1366|하나센터|북한이탈)/.test(text)) {
        return 'family-gender';
    }
    // 8. 청소년 ('쉼터' 단일어 대신 '청소년쉼터' 사용 — 노인/아동/장애인 쉼터 오분류 방지)
    if (/(청소년|청소년쉼터|꿈드림|학교밖|청소년자립지원|회복지원)/.test(text)) {
        return 'youth';
    }
    // 9. 장애인 ('그룹홈'이 아동 규칙에 먼저 걸리지 않도록 장애/재활을 아동보다 우선 판별)
    if (/(장애인|장애|직업재활|보호작업장|근로사업장|발달장애|장애인주간보호|주간이용|활동지원|보조기기|수어)/.test(text)) {
        return 'disability';
    }
    // 10. 아동 ('공동생활가정' 단일어 대신 '아동공동생활가정' 사용)
    if (/(아동|어린이|지역아동센터|다함께돌봄|드림스타트|아동양육|아동공동생활가정|그룹홈|아동보호전문|가정위탁|자립지원전담|보육)/.test(text)) {
        return 'child';
    }
    // 11. 노인·통합돌봄
    if (/(노인|어르신|요양원|요양시설|방문요양|장기요양|재가노인|데이케어|주야간보호|시니어|치매|노인보호전문|통합돌봄|양로)/.test(text)) {
        return 'elderly';
    }
    return null;
}

/**
 * 기존 6대 카테고리 / 자동수집 공고 문자열을 12대 세분화 분야(fieldId)로 2단계 스마트 분류
 * - 1단계: 기관명·공고제목(company + role) 우선 판별 (레거시 '의료/정신건강' 등 복합 태그 오염 차단)
 * - 2단계: 1단계 미매칭 시 수집 출처·메모·카테고리 문맥 보완
 */
export function classifyJobToFieldId(job) {
    if (job?.fieldId && getFieldById(job.fieldId)) {
        return job.fieldId;
    }
    const titleText = `${job?.company || ''} ${job?.role || ''}`.toLowerCase();
    const titleMatch = matchFieldRules(titleText);
    if (titleMatch) {
        return titleMatch;
    }

    const metaText = `${job?.memo || ''} ${job?.category || ''}`.toLowerCase();
    if (/한국정신건강사회복지사협회/.test(metaText)) return 'mental-health';
    if (/대한의료사회복지사협회/.test(metaText)) return 'medical';
    if (/(kcoc|국제개발협력민간협의회)/.test(metaText)) return 'ngo';

    // 레거시 복합 검색 태그("의료/정신건강", "아동/청소년")가 제목 외 공고를 과점유하지 않도록 중화
    const normalizedMeta = metaText
        .replace(/의료\/정신건강/g, '의료')
        .replace(/아동\/청소년/g, '아동')
        .replace(/가족\/여성\/성평등/g, '가족센터');

    return matchFieldRules(normalizedMeta) || 'community-selfreliance';
}

/**
 * 공고의 트랙 분류 (인턴/수련/계약 vs 신입/정규)
 */
export function classifyJobTrack(job) {
    if (job?.track) {
        if (['수련', '전문수련', '법정수련'].includes(job.track)) return '수련';
        if (['인턴', '청년인턴', '체험형인턴'].includes(job.track)) return '인턴';
        if (['계약직', '전담', '사업전담', '전담계약직'].includes(job.track)) return '계약직';
        if (['신입', '정규직', '신입·정규직'].includes(job.track)) return '신입·정규직';
        return job.track;
    }
    const text = `${job?.role || ''} ${job?.memo || ''} ${job?.category || ''}`.toLowerCase();
    if (/(수련|임상수련|2급 수련|수련생)/.test(text)) return '수련';
    if (/(인턴|청년인턴|체험형|서포터즈|yp|멘토링)/.test(text)) return '인턴';
    if (/(계약직|전담|대체인력|단기|코디네이터|사례관리사)/.test(text)) return '계약직';
    return '신입·정규직';
}

