export function getRegionGroup(region) {
    if (['서울', '경기', '인천'].includes(region)) return '수도권';
    if (['부산', '대구', '울산', '경남', '경북'].includes(region)) return '영남권';
    if (['대전', '세종', '충남', '충북'].includes(region)) return '충청권';
    if (['광주', '전북', '전남'].includes(region)) return '호남권';
    if (region === '강원') return '강원권';
    if (region === '제주') return '제주권';
    return '수도권';
}

