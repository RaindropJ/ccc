    function matchHierarchyNodesForFacility(facilityTerm, parentCat, allNodes) {
        if (!facilityTerm) return allNodes;
        const term = String(facilityTerm).trim();
        let clean = term.replace(/^[•\s]+/, '').replace(/\s*\(.*?\)\s*/g, '').trim();
        clean = clean.replace(/(등|포함|연계|제공사업장)\s*$/g, '').trim();

        const matchByRule = (r, pool) => {
            if (!r) return [];
            const dids = Array.isArray(r.domainIds) ? r.domainIds : (r.domainId ? [r.domainId] : []);
            const ftypes = r.facilityTypes || [];
            const l1s = r.level1 || [];
            return pool.filter(n =>
                (dids.length === 0 || dids.includes(n.domainId)) &&
                (ftypes.includes(n.facilityType) || l1s.some(l => (n.level1 || '').includes(l)))
            );
        };

        // 1. Direct rule match
        const rule = FACILITY_MAPPING_RULES[clean] || FACILITY_MAPPING_RULES[term];
        if (rule) {
            const matched = matchByRule(rule, allNodes);
            if (matched.length > 0) return matched;
        }

        // 1-2. If parentCat maps directly to a rule, scope matching inside parentCat's domain/nodes first
        const cleanParent = parentCat
            ? String(parentCat).replace(/^[•\s]+/, '').replace(/\s*\(.*?\)\s*/g, '').replace(/(등|포함|연계|제공사업장)\s*$/g, '').trim()
            : '';
        const parentRule = parentCat ? (FACILITY_MAPPING_RULES[cleanParent] || FACILITY_MAPPING_RULES[parentCat]) : null;
        if (parentRule) {
            const scopedNodes = matchByRule(parentRule, allNodes);
            if (scopedNodes.length > 0) {
                const subHit = scopedNodes.filter(n =>
                    (n.facilityType && (n.facilityType.includes(clean) || clean.includes(n.facilityType))) ||
                    (n.level1 && n.level1.includes(clean)) ||
                    (n.level2 && n.level2.includes(clean)) ||
                    (n.level3 && n.level3.includes(clean)) ||
                    (n.details || []).some(d => d.includes(clean))
                );
                return subHit.length > 0 ? subHit : scopedNodes;
            }
        }

        // 2. Exact or substring match on facilityType
        let m = allNodes.filter(n => (n.facilityType && (n.facilityType.includes(clean) || clean.includes(n.facilityType))));
        if (m.length > 0) return m;

        // 3. Match on level1, level2, or level3
        m = allNodes.filter(n => (n.level1 && n.level1.includes(clean)) || (n.level2 && n.level2.includes(clean)) || (n.level3 && n.level3.includes(clean)));
        if (m.length > 0) return m;

        // 4. Token match
        const tokens = clean.split(/[\s·/]+/).filter(t => t.length >= 2 && !['시설', '지원', '복지', '기관', '센터'].includes(t));
        if (tokens.length > 0) {
            m = allNodes.filter(n => tokens.some(t => (n.facilityType && n.facilityType.includes(t)) || (n.level1 && n.level1.includes(t)) || (n.level2 && n.level2.includes(t)) || (n.level3 && n.level3.includes(t))));
            if (m.length > 0) return m;
        }

        // 5. Parent category fallback
        if (parentCat && parentCat !== facilityTerm) {
            return matchHierarchyNodesForFacility(parentCat, null, allNodes);
        }

        return allNodes;
    }

