def main():
    db_path = 'src/data/welfare-hierarchy-db.js'
    with open(db_path, 'r', encoding='utf-8') as f:
        text = f.read()

    # Find WELFARE_HIERARCHY_NODES = [ ... ];
    start_pos = text.find('const WELFARE_HIERARCHY_NODES = [')
    end_pos = text.find('];', start_pos)
    if start_pos == -1 or end_pos == -1:
        print("Error: Could not locate WELFARE_HIERARCHY_NODES array")
        return

    # Extract existing array text
    array_content = text[start_pos + len('const WELFARE_HIERARCHY_NODES = ['):end_pos].strip()
    
    # Load existing nodes via json or regex
    # Since array_content is JavaScript object notation (valid JSON inside), let's parse
    try:
        existing_nodes = json.loads('[' + array_content + ']')
        print(f"Loaded {len(existing_nodes)} existing nodes via json.loads")
    except Exception as e:
        print("JSON parse failed, attempting regex extraction:", e)
        # fallback
        return

    # Check for ID duplicates
    existing_ids = set(n['id'] for n in existing_nodes)
    new_nodes_to_add = []
    for node in NEW_NODES:
        if node['id'] in existing_ids:
            print(f"Warning: Node ID '{node['id']}' already exists, skipping")
        else:
            new_nodes_to_add.append(node)

    print(f"Adding {len(new_nodes_to_add)} new nodes...")
    combined_nodes = existing_nodes + new_nodes_to_add
    print(f"Combined total nodes: {len(combined_nodes)}")

    # Format combined array to clean JS JSON with 2 spaces indent
    formatted_nodes = json.dumps(combined_nodes, ensure_ascii=False, indent=2)
    
    # Replace in file
    new_text = text[:start_pos] + f"const WELFARE_HIERARCHY_NODES = {formatted_nodes};" + text[end_pos + 2:]

    with open(db_path, 'w', encoding='utf-8') as f:
        f.write(new_text)

    print("Successfully updated src/data/welfare-hierarchy-db.js!")

if __name__ == '__main__':
    main()
